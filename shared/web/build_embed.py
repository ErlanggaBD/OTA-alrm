#!/usr/bin/env python3
"""Generate firmware-arduino/MedGasAlarm/web_ui.h from shared/web assets.

The Arduino WebServer serves these strings directly from flash (PROGMEM).
Run this after editing shared/web/*.
"""
from __future__ import annotations

import argparse
from pathlib import Path

FILES = {
    "INDEX_HTML": "index.html",
    "SETTINGS_HTML": "settings.html",
    "SETUP_HTML": "setup.html",
    "LOGIN_HTML": "login.html",
    "LOCKED_HTML": "locked.html",
    "STYLE_CSS": "style.css",
    "APP_JS": "app.js",
}

DELIM = "MGUI_EMBED"


def c_literal(name: str, text: str) -> str:
    if f"){DELIM}\"" in text:
        raise SystemExit(f"{name}: content contains raw-string delimiter")
    return (
        f"static const char {name}[] PROGMEM = R\"{DELIM}(\n"
        f"{text}\n"
        f"){DELIM}\";\n"
    )


def main() -> None:
    here = Path(__file__).resolve().parent
    repo = here.parent.parent
    default_out = repo / "firmware-arduino" / "MedGasAlarm" / "web_ui.h"

    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=default_out)
    args = parser.parse_args()

    parts = [
        "// AUTO-GENERATED by shared/web/build_embed.py — do not edit manually.\n",
        "#pragma once\n",
        "#include <Arduino.h>\n\n",
    ]
    for name, filename in FILES.items():
        path = here / filename
        if not path.exists():
            raise SystemExit(f"missing asset: {path}")
        parts.append(f"// {filename}\n")
        parts.append(c_literal(name, path.read_text(encoding="utf-8")))

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(parts), encoding="utf-8")
    total = sum((here / f).stat().st_size for f in FILES.values())
    print(f"wrote {args.out} ({total} bytes of assets)")


if __name__ == "__main__":
    main()
